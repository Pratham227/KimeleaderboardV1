export function computeTenure(employee) {
  return Number(employee?.tenure) || 0
}

export function categoryForTenure(tenureMonths) {
  const tenure = Number(tenureMonths) || 0

  if (tenure > 6) return 'King'
  if (tenure > 3) return 'Prince'

  return 'Warrior'
}

export function categoryForEmployee(employee) {
  return categoryForTenure(computeTenure(employee))
}

export function initialsOf(name = '') {
  return String(name)
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map(part => part[0])
    .join('')
    .toUpperCase()
}

export function getRankedEmployees() {
  return EMPLOYEES_RAW.filter(
    employee => !employee.isAdmin && employee.active !== false
  )
}

export function findEmployeeByEmail(email) {
  if (!email) return null

  const normalized = String(email).trim().toLowerCase()

  return EMPLOYEES_RAW.find(
    employee => employee.email.toLowerCase() === normalized
  ) || null
}

export function getEmployeesByVertical(vertical) {
  const employees = getRankedEmployees()

  if (!vertical) return employees

  const normalized = String(vertical).trim().toUpperCase()

  return employees.filter(employee => {
    const employeeVertical = String(employee.vertical || 'DLP').toUpperCase()

    return (
      employeeVertical === normalized ||
      employeeVertical === 'ALL'
    )
  })
}
